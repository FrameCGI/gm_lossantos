import argparse
import math
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOURS = [0, 5, 6, 7, 10, 13, 16, 17, 18, 19, 20, 21, 22]
SUN_ELEV_DEG = 52.0  # baked sun_shadow.gvsd elevation


def timecycle(path, hour):
    txt = open(path, encoding='utf-8').read()
    region = txt.split('<region name="GLOBAL">', 1)[1].split('</region>', 1)[0]
    col = HOURS.index(hour)
    out = {}
    for name, vals in re.findall(r'<([a-z0-9_]+)>([^<]*)</\1>', region):
        v = vals.split()
        if len(v) == 13:
            out[name] = float(v[col])
    return out


def visualsettings(path):
    out = {}
    for ln in open(path, encoding='utf-8', errors='replace'):
        p = ln.split()
        if len(p) >= 2 and not ln.lstrip().startswith(('#', '/')):
            try:
                out[p[0]] = float(p[1])
            except ValueError:
                pass
    return out


def rgb(tc, base, mult=None):
    m = tc[mult] if mult else 1.0
    return [tc[base + '_r'] * m, tc[base + '_g'] * m, tc[base + '_b'] * m]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--hour', type=int, default=13)
    ap.add_argument('--weather', default='w_extrasunny')
    ap.add_argument('--exposure-point', type=float, default=1.6,
                    help='filmic input value the sunlit reference maps to')
    ap.add_argument('--amb-scale', type=float, default=1.0,
                    help='preview: multiply the three ambient terms (runtime convar gtav_cl_sun_ambient)')
    ap.add_argument('--write', help='write a C header with the derived constants')
    a = ap.parse_args()

    tc = timecycle(os.path.join(REPO, 'refdata', a.weather + '.xml'), a.hour)
    vs = visualsettings(os.path.join(REPO, 'refdata', 'visualsettings.dat'))
    F = {k: vs['Tonemapping.bright.filmic.' + k] for k in 'ABCDEFW'}

    sun = rgb(tc, 'light_dir_col', 'light_dir_mult')
    dir_amb = rgb(tc, 'light_directional_amb_col', 'light_directional_amb_intensity')
    sky = rgb(tc, 'light_natural_amb_down_col', 'light_natural_amb_down_intensity')
    bounce = rgb(tc, 'light_natural_amb_up_col', 'light_natural_amb_up_intensity')

    def hable(x):
        A, B, C, D, E, Fv = F['A'], F['B'], F['C'], F['D'], F['E'], F['F']
        return ((x * (A * x + C * B) + D * E) / (x * (A * x + B) + D * Fv)) - E / Fv

    sl = math.sin(math.radians(SUN_ELEV_DEG))

    s = a.amb_scale

    def L(ndl, nz, vis):
        return [sun[i] * max(0.0, ndl) * vis + s * (dir_amb[i] * (0.5 + 0.5 * ndl)
                + bounce[i] + (sky[i] - bounce[i]) * (0.5 + 0.5 * nz)) for i in range(3)]

    ref = L(sl, 1.0, 1.0)
    ref_lum = 0.2126 * ref[0] + 0.7152 * ref[1] + 0.0722 * ref[2]
    k = a.exposure_point / ref_lum
    white = hable(F['W'])

    def colour(ndl, nz, vis):
        l = L(ndl, nz, vis)
        num = [hable(k * c) / white for c in l]
        den = hable(k * ref_lum) / white
        return [min(1.0, c / den) for c in num]

    print('timecycle %s %02d:00  filmic A..W %s' % (a.weather, a.hour,
          ' '.join('%s=%g' % kv for kv in F.items())))
    print('sun %s  dirAmb %s  sky %s  bounce %s' % tuple(
        '(%.2f %.2f %.2f)' % tuple(v) for v in (sun, dir_amb, sky, bounce)))
    print('exposure k = %.5f (reference luminance %.2f -> filmic %.2f)' % (k, ref_lum, a.exposure_point))
    cases = [('sunlit up-facing (ref)', sl, 1.0, 1.0),
             ('sunlit wall facing sun', math.cos(math.radians(SUN_ELEV_DEG)), 0.0, 1.0),
             ('shadowed ground', sl, 1.0, 0.0),
             ('shadowed wall (sun side)', math.cos(math.radians(SUN_ELEV_DEG)), 0.0, 0.0),
             ('wall facing away from sun', -math.cos(math.radians(SUN_ELEV_DEG)), 0.0, 1.0),
             ('down-facing (underside)', -sl, -1.0, 1.0)]
    for label, ndl, nz, vis in cases:
        c = colour(ndl, nz, vis)
        print('  %-28s rgb %.3f %.3f %.3f' % (label, *c))

    if a.write:
        with open(os.path.join(REPO, a.write), 'w', encoding='utf-8', newline='\n') as fh:
            fh.write('/* Generated by tools/timecycle_light.py from the user\'s own GTA V\n'
                     '   %s.xml %02d:00 + visualsettings.dat (numbers only). */\n' % (a.weather, a.hour))
            fh.write('#ifndef GTAV_LIGHT_TC_H\n#define GTAV_LIGHT_TC_H\n')
            for nm, v in (('SUN', sun), ('DIRAMB', dir_amb), ('SKY', sky), ('BOUNCE', bounce)):
                fh.write('static const float TC_%s[3] = { %.5ff, %.5ff, %.5ff };\n' % (nm, *v))
            fh.write('static const float TC_FILMIC[7] = { %.5ff, %.5ff, %.5ff, %.5ff, %.5ff, %.5ff, %.5ff }; /* A B C D E F W */\n'
                     % tuple(F[c] for c in 'ABCDEFW'))
            fh.write('static const float TC_EXPOSURE_K = %.6ff;\n' % k)
            fh.write('#endif\n')
        print('wrote', a.write)


if __name__ == '__main__':
    main()
